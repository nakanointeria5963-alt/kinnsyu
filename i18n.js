  const DICT = { ja, en };
  let setting = 'auto';

  function detect() {
    const l = (navigator.language || 'ja').toLowerCase();
    return l.startsWith('ja') ? 'ja' : 'en';
  }
  function lang() { return setting === 'auto' ? detect() : setting; }
  function locale() { return lang() === 'ja' ? 'ja-JP' : 'en-US'; }
  function setLang(s) { setting = (s === 'ja' || s === 'en') ? s : 'auto'; }
  function t(key, vars) {
    let s = DICT[lang()][key];
    if (s == null) s = DICT.ja[key];
    if (s == null) return key;
    if (vars) {
      for (const k in vars) s = s.split('{' + k + '}').join(vars[k]);
      /* 複数形: {n?day|days} → vars.n が 1 なら前者 */
      s = s.replace(/\{(\w+)\?([^|}]*)\|([^}]*)\}/g, (m, k, one, many) =>
        Number(vars[k]) === 1 ? one : many);
    }
    return s;
  }
  function dows() {
    return lang() === 'ja'
      ? ['日', '月', '火', '水', '木', '金', '土']
      : ['Su', 'Mo', 'Tu', 'We', 'Th', 'Fr', 'Sa'];
  }

  return { t, lang, locale, setLang, dows };
