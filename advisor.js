/* ---- 乱数・ハッシュ ---- */
function hashSeed(str) {
  let h = 0x811c9dc5;
  for (let i = 0; i < str.length; i++) { h ^= str.charCodeAt(i); h = Math.imul(h, 0x01000193); }
  return h >>> 0;
}
function rng(seed) {
  let s = seed >>> 0;
  return function () {
    s = (Math.imul(s ^ (s >>> 15), 1 | s) >>> 0);
    s = (s + Math.imul(s ^ (s >>> 7), 61 | s)) >>> 0;
    return ((s ^ (s >>> 14)) >>> 0) / 4294967296;
  };
}
/* 直近に使ったものを避けて選ぶ */
function pick(pool, rand, history, keep) {
  let avail = pool.filter(s => !history.includes(s));
  if (avail.length === 0) avail = pool.slice();
  const s = avail[Math.floor(rand() * avail.length)];
  history.push(s);
  while (history.length > keep) history.shift();
  return s;
}

function ageFrom(birthDate) {
  if (!birthDate) return null;
  const b = new Date(birthDate), t = new Date();
  if (isNaN(b)) return null;
  let a = t.getFullYear() - b.getFullYear();
  const m = t.getMonth() - b.getMonth();
  if (m < 0 || (m === 0 && t.getDate() < b.getDate())) a--;
  return (a >= 0 && a < 130) ? a : null;
}

/* history はステップ別の配列を持つオブジェクト（永続化される）。破壊的に更新する。 */
function generate({ days, age, date, salt = 0, history }) {
  history = history || {};
  for (const k of ['med', 'age', 'trivia', 'tip', 'closing']) if (!history[k]) history[k] = [];

  const rand = rng(hashSeed(`${date}|${salt}|${age == null ? 'x' : age}|${days}`));
  const grp = ageGroup(age);
  const label = ageLabel(age);

  const med = pick(MED[stageKey(days)], rand, history.med, 4);
  const ageNote = pick(AGE[grp], rand, history.age, 2);
  const trivia = pick(TRIVIA, rand, history.trivia, 8);
  const tip = pick(TIP, rand, history.tip, 5);
  const closing = pick(CLOSING, rand, history.closing, 2);

  const head = days <= 0
    ? (label ? `断酒スタート、${label}のあなたへ。` : '断酒スタート。よく決心しました。')
    : (label ? `断酒 ${days} 日目、${label}のあなたへ。` : `断酒 ${days} 日目のあなたへ。`);

  const text =
    `${head}\n\n` +
    `🩺 ${med}\n\n` +
    `${ageNote}\n\n` +
    `💡 豆知識: ${trivia}\n\n` +
    `${tip} ${closing}`;

  return { text };
}

